class PolicyContractError(ValueError):
    """Raised when prior evidence conflicts with the frozen R3 policy."""


def _sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def sha256_file(path: Path) -> str:
    return _sha256_bytes(path.read_bytes())


def canonical_content_hash(document: dict[str, Any]) -> str:
    value = dict(document)
    value.pop("deterministic_content_sha256", None)
    encoded = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True, allow_nan=False).encode("utf-8")
    return _sha256_bytes(encoded)


def serialize_policy(document: dict[str, Any]) -> bytes:
    return (json.dumps(document, sort_keys=True, indent=2, ensure_ascii=True, allow_nan=False) + "\n").encode("utf-8")


def _formula(name: str, expression: str, notes: str) -> dict[str, str]:
    return {"name": name, "formula": expression, "notes": notes}


