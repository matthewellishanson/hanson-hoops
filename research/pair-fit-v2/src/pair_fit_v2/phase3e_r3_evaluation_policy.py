def classify_evaluation(stage_a_pass: bool, stage_b_pass: bool, mae_improvement: float, rmse_improvement: float) -> str:
    """Apply the frozen mutually exclusive Phase 3E-R3 classification rule."""
    if not stage_a_pass or not stage_b_pass or not math.isfinite(mae_improvement) or not math.isfinite(rmse_improvement):
        return "INVALID EVALUATION — IMPLEMENTATION OR CONTRACT FAILURE"
    if mae_improvement <= 0.0:
        return "VALID DEVELOPMENT-HOLDOUT SCIENTIFIC FAILURE"
    if mae_improvement >= 0.10 and rmse_improvement >= 0.0:
        return "VALID DEVELOPMENT-HOLDOUT PASS"
    return "VALID DEVELOPMENT-HOLDOUT MIXED RESULT"


